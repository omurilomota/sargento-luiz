/**
 * Converte um caractere da legenda no tipo de tile correspondente.
 * `P`, `E`, `B`, `N` e `R` são chão andável por cima do seu conteúdo.
 */
export function tileKindAt(ch: string): TileKind {
  switch (ch) {
    case '#': return 'wall';
    case ',': return 'decor';
    case '^': return 'hazard';
    case 'c': return 'crate';
    case 'b': return 'barrel';
    default: return 'floor';
  }
}

/** Verifica se um tile bloqueia o movimento. */
export function isBlocking(ch: string): boolean {
  const k = tileKindAt(ch);
  return k === 'wall';
}

/** Verifica se um tile é piso andável (não bloqueia). */
export function isWalkable(ch: string): boolean {
  return ch !== '#';
}
