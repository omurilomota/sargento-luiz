/** Prova: senha do modo dev dá build máxima; senha errada não dá. */
import { chromium } from 'playwright';
import { createServer } from 'http';
import { readFile } from 'fs/promises';
import { existsSync } from 'fs';
import { extname, join } from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';
const RAIZ = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(RAIZ, 'dist');
const MIME = { '.html':'text/html', '.js':'text/javascript', '.png':'image/png', '.ogg':'audio/ogg' };
const s = createServer(async (req,res)=>{ const u=(req.url||'/').split('?')[0]; const p=join(DIST,u==='/'?'index.html':decodeURIComponent(u)); if(!existsSync(p)){res.writeHead(404);res.end();return;} res.writeHead(200,{'Content-Type':MIME[extname(p)]||'application/octet-stream'}); res.end(await readFile(p)); });
await new Promise(r=>s.listen(0,'127.0.0.1',r));
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', args:['--no-sandbox','--disable-gpu','--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport:{width:1280,height:720} });
const erros=[]; p.on('pageerror',e=>erros.push(e.message));
await p.goto(`http://127.0.0.1:${s.address().port}/`,{waitUntil:'networkidle'});
await p.waitForTimeout(500);
const errada = await p.evaluate(()=>window.__ashfall.modoDev('senha-errada'));
const certa = await p.evaluate(()=>window.__ashfall.modoDev('desenvolvefacil123'));
const ativo = await p.evaluate(()=>window.__ashfall.modoDevAtivo());
const stats = await p.evaluate(()=>({ hp: window.__ashfall.telemetria().maxHp, armas: window.__ashfall.arma().qualidade }));
console.log('senha errada aceita:', errada, errada===false?'OK':'FALHA');
console.log('senha certa aceita:', certa, certa===true?'OK':'FALHA');
console.log('modo dev ativo:', ativo);
console.log('build maxima:', JSON.stringify(stats), stats.hp>=300 && stats.armas==='lendaria'?'OK':'FALHA');
console.log('pageerrors:', erros.length);
await b.close(); s.close();
